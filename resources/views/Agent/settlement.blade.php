<script src="https://cdn.jsdelivr.net/npm/sweetalert2@11"></script>
<script>
    const searchUrl = "{{ route('agent.settlement.search') }}";
    const generateTokenUrl = "{{ route('agent.settlement.generate-token') }}";
    const cancelTokenUrl = "{{ route('agent.settlement.cancel-token') }}";
    const csrfToken = "{{ csrf_token() }}";
    const orgName = @json($org_name);
    const agentName = @json($agent_name);
    let printRows = [];
    let currentToken = @json($settle_token ?? '');
    let currentDenom = null;

    function fmtAmt(n) {
        return (parseFloat(n) || 0).toFixed(2);
    }

    function denomTotal(d) {
        d = d || {};
        return (parseInt(d.coin, 10) || 0)
            + ((parseInt(d.rs_5, 10) || 0) * 5)
            + ((parseInt(d.rs_10, 10) || 0) * 10)
            + ((parseInt(d.rs_20, 10) || 0) * 20)
            + ((parseInt(d.rs_50, 10) || 0) * 50)
            + ((parseInt(d.rs_100, 10) || 0) * 100)
            + ((parseInt(d.rs_200, 10) || 0) * 200)
            + ((parseInt(d.rs_500, 10) || 0) * 500);
    }

    function denomPairs(d) {
        if (!d) return [];
        return [
            [500, d.rs_500],
            [200, d.rs_200],
            [100, d.rs_100],
            [50, d.rs_50],
            [20, d.rs_20],
            [10, d.rs_10],
            [5, d.rs_5],
            [1, d.coin]
        ];
    }

    function denomLines(d) {
        return denomPairs(d).map(([note, qty]) => note + '|' + (parseInt(qty, 10) || 0));
    }

    function denomBoxHtml(d, withTotal) {
        if (!d) return '';
        const rows = denomPairs(d).map(([note, qty]) => `
            <div class="denom-row">
                <div class="denom-note">${note}</div>
                <div class="denom-sep"></div>
                <div class="denom-qty"><span class="denom-qty-val">${parseInt(qty, 10) || 0}</span></div>
            </div>
        `).join('');
        const total = withTotal
            ? `<div class="denom-total-line"><span>Total</span><span>₹ ${fmtAmt(d.denom_total ?? denomTotal(d))}</span></div>`
            : '';
        return `<div class="denom-box">${rows}</div>${total}`;
    }

    function denomHtml(d) {
        return denomBoxHtml(d, true);
    }

    function setActiveDenom(denom) {
        currentDenom = denom || null;
        if (currentDenom) {
            $('#activeDenomBox').html(denomHtml(currentDenom)).removeClass('d-none');
        } else {
            $('#activeDenomBox').html('').addClass('d-none');
        }
    }

    function setActiveToken(token, denom) {
        currentToken = (token || '').trim();
        if (arguments.length > 1) {
            setActiveDenom(denom);
        }
        if (currentToken) {
            $('#activeTokenValue').text(currentToken);
            $('#activeTokenBox').removeClass('d-none');
            $('#generateTokenBtnText').text('View Token');
        } else {
            $('#activeTokenValue').text('');
            $('#activeTokenBox').addClass('d-none');
            $('#generateTokenBtnText').text('Generate Token');
            setActiveDenom(null);
        }
        updateGenerateTokenBtn();
    }

    function updateGenerateTokenBtn() {
        $('#generateTokenBtn').prop('disabled', !printRows.length && !currentToken);
    }

    function calcModeTotals(data) {
        const totals = { cash: 0, bank: 0, credit: 0, net: 0 };
        (data || []).forEach((row) => {
            const amt = parseFloat(row.Net_Amt) || 0;
            const mode = parseInt(row.Pay_Mode, 10) || 0;
            totals.net += amt;
            if (mode === 1) totals.cash += amt;
            else if (mode === 2) totals.bank += amt;
            else if (mode === 3) totals.credit += amt;
        });
        return totals;
    }

    function updateSummary(data) {
        const totals = calcModeTotals(data);
        $('#cashTotal').text('₹ ' + fmtAmt(totals.cash));
        $('#bankTotal').text('₹ ' + fmtAmt(totals.bank));
        $('#creditTotal').text('₹ ' + fmtAmt(totals.credit));
        $('#netTotalCell').text(fmtAmt(totals.net));
        if ((data || []).length) {
            $('#reportFoot').removeClass('d-none');
        } else {
            $('#reportFoot').addClass('d-none');
        }
        return totals;
    }

    function renderRows(data) {
        if (!data.length) {
            printRows = [];
            $('#reportBody').html('<tr><td colspan="6" class="text-center text-muted">No unsettled transactions</td></tr>');
            $('#printBtn').prop('disabled', true);
            updateSummary([]);
            updateGenerateTokenBtn();
            return;
        }
        printRows = data;
        let html = '';
        data.forEach((row, idx) => {
            html += `<tr>
                <td>${idx + 1}</td>
                <td>${row.Invoice_No ?? ''}</td>
                <td>${row.Invoice_Date ? siDate.toDisplay(row.Invoice_Date) : ''}</td>
                <td>${row.Customer_Name ?? ''}</td>
                <td>${row.Trans_Mode ?? '-'}</td>
                <td class="text-end">${fmtAmt(row.Net_Amt)}</td>
            </tr>`;
        });
        $('#reportBody').html(html);
        updateSummary(data);
        $('#printBtn').prop('disabled', false);
        updateGenerateTokenBtn();
    }

    function showTokenPopup(message, token, alreadyExists, denom) {
        const denomBlock = denom
            ? `<div class="mt-3 text-start">${denomHtml(denom)}</div>`
            : '';
        Swal.fire({
            title: alreadyExists ? 'Existing Token' : 'Token Generated',
            html: `<div class="mb-2">${message || ''}</div>
                   <div class="fs-4 fw-bold"><code>${token || ''}</code></div>
                   ${denomBlock}
                   ${alreadyExists ? '<div class="mt-2 text-muted small">Token cannot be regenerated until admin settles, or cancel it below.</div>' : ''}`,
            icon: alreadyExists ? 'info' : 'success',
            showCancelButton: true,
            confirmButtonText: 'OK',
            cancelButtonText: 'Cancel Token',
            reverseButtons: true,
            focusCancel: false
        }).then(function (result) {
            if (result.dismiss === Swal.DismissReason.cancel) {
                cancelActiveToken();
            }
        });
    }

    function openDenominationForm(cashTotal) {
        return Swal.fire({
            title: 'Cash Denomination',
            html: `
                <div class="text-start small mb-2">Cash Total: <b>₹ ${fmtAmt(cashTotal)}</b> <span class="text-muted">(denomination must match exactly)</span></div>
                <div class="denom-box">
                    <div class="denom-row"><div class="denom-note">500</div><div class="denom-sep"></div><div class="denom-qty"><input type="text" inputmode="numeric" autocomplete="off" id="swal_rs500"></div></div>
                    <div class="denom-row"><div class="denom-note">200</div><div class="denom-sep"></div><div class="denom-qty"><input type="text" inputmode="numeric" autocomplete="off" id="swal_rs200"></div></div>
                    <div class="denom-row"><div class="denom-note">100</div><div class="denom-sep"></div><div class="denom-qty"><input type="text" inputmode="numeric" autocomplete="off" id="swal_rs100"></div></div>
                    <div class="denom-row"><div class="denom-note">50</div><div class="denom-sep"></div><div class="denom-qty"><input type="text" inputmode="numeric" autocomplete="off" id="swal_rs50"></div></div>
                    <div class="denom-row"><div class="denom-note">20</div><div class="denom-sep"></div><div class="denom-qty"><input type="text" inputmode="numeric" autocomplete="off" id="swal_rs20"></div></div>
                    <div class="denom-row"><div class="denom-note">10</div><div class="denom-sep"></div><div class="denom-qty"><input type="text" inputmode="numeric" autocomplete="off" id="swal_rs10"></div></div>
                    <div class="denom-row"><div class="denom-note">5</div><div class="denom-sep"></div><div class="denom-qty"><input type="text" inputmode="numeric" autocomplete="off" id="swal_rs5"></div></div>
                    <div class="denom-row"><div class="denom-note">1</div><div class="denom-sep"></div><div class="denom-qty"><input type="text" inputmode="numeric" autocomplete="off" id="swal_coin"></div></div>
                </div>
                <div class="denom-total-line">
                    <span>Denomination Total</span>
                    <span id="swal_denom_total">₹ 0.00</span>
                </div>
            `,
            showCancelButton: true,
            confirmButtonText: 'Generate Token',
            cancelButtonText: 'Cancel',
            allowOutsideClick: false,
            allowEscapeKey: false,
            focusConfirm: false,
            didOpen: () => {
                const cashRounded = Math.round((parseFloat(cashTotal) || 0) * 100) / 100;
                const denomInputs = '#swal_rs500, #swal_rs200, #swal_rs100, #swal_rs50, #swal_rs20, #swal_rs10, #swal_rs5, #swal_coin';
                const recalc = () => {
                    const d = {
                        rs_500: $('#swal_rs500').val(),
                        rs_200: $('#swal_rs200').val(),
                        rs_100: $('#swal_rs100').val(),
                        rs_50: $('#swal_rs50').val(),
                        rs_20: $('#swal_rs20').val(),
                        rs_10: $('#swal_rs10').val(),
                        rs_5: $('#swal_rs5').val(),
                        coin: $('#swal_coin').val()
                    };
                    const total = Math.round(denomTotal(d) * 100) / 100;
                    const $el = $('#swal_denom_total');
                    $el.text('₹ ' + fmtAmt(total));
                    if (total > cashRounded) {
                        $el.css('color', '#dc2626');
                    } else if (Math.abs(total - cashRounded) > 0.009) {
                        $el.css('color', '#d97706');
                    } else {
                        $el.css('color', '#16a34a');
                    }
                };
                $(denomInputs).on('input', function () {
                    this.value = String(this.value || '').replace(/\D/g, '');
                    recalc();
                });
                recalc();
            },
            preConfirm: () => {
                const data = {
                    rs_500: parseInt($('#swal_rs500').val(), 10) || 0,
                    rs_200: parseInt($('#swal_rs200').val(), 10) || 0,
                    rs_100: parseInt($('#swal_rs100').val(), 10) || 0,
                    rs_50: parseInt($('#swal_rs50').val(), 10) || 0,
                    rs_20: parseInt($('#swal_rs20').val(), 10) || 0,
                    rs_10: parseInt($('#swal_rs10').val(), 10) || 0,
                    rs_5: parseInt($('#swal_rs5').val(), 10) || 0,
                    coin: parseInt($('#swal_coin').val(), 10) || 0,
                    settle_date: new Date().toISOString().slice(0, 10)
                };
                const total = Math.round(denomTotal(data) * 100) / 100;
                const cashRounded = Math.round((parseFloat(cashTotal) || 0) * 100) / 100;
                if (cashRounded > 0 && total <= 0) {
                    Swal.showValidationMessage('Enter cash denomination before generating token');
                    return false;
                }
                if (total > cashRounded) {
                    Swal.showValidationMessage('Denomination total cannot exceed Cash Total (₹ ' + fmtAmt(cashRounded) + ')');
                    return false;
                }
                if (Math.abs(total - cashRounded) > 0.009) {
                    Swal.showValidationMessage('Denomination total must match Cash Total (₹ ' + fmtAmt(cashRounded) + ')');
                    return false;
                }
                return data;
            }
        });
    }

    function cancelActiveToken() {
        if (!currentToken) {
            Swal.fire('Info', 'No active settlement token to cancel', 'info');
            return;
        }

        Swal.fire({
            title: 'Cancel Token?',
            text: 'This will clear the current settlement token and denomination. You can generate a new one later.',
            icon: 'warning',
            showCancelButton: true,
            confirmButtonText: 'Yes, Cancel Token',
            cancelButtonText: 'Keep Token'
        }).then(function (result) {
            if (!result.isConfirmed) return;

            $.ajax({
                url: cancelTokenUrl,
                method: 'POST',
                data: { _token: csrfToken },
                success: function (res) {
                    setActiveToken('', null);
                    Swal.fire('Cancelled', res.message || 'Settlement token cancelled', 'success');
                },
                error: function (xhr) {
                    Swal.fire('Error', xhr.responseJSON?.message || 'Failed to cancel token', 'error');
                }
            });
        });
    }

    function loadSettlementData() {
        $('#reportBody').html('<tr><td colspan="6" class="text-center">Loading...</td></tr>');
        $.get(searchUrl, function (res) {
            const data = Array.isArray(res) ? res : (res.rows || []);
            const token = Array.isArray(res) ? '' : (res.settle_token || '');
            const denom = Array.isArray(res) ? null : (res.denomination || null);
            renderRows(data);
            setActiveToken(token, denom);
        }).fail(function (xhr) {
            Swal.fire('Error', xhr.responseJSON?.message || 'Failed to load settlement data', 'error');
            printRows = [];
            $('#reportBody').html('<tr><td colspan="6" class="text-center text-danger">Failed to load</td></tr>');
            updateSummary([]);
            updateGenerateTokenBtn();
            $('#printBtn').prop('disabled', true);
        });
    }

    function printReport() {
        if (!printRows.length) {
            Swal.fire('Error', 'No data to print', 'error');
            return;
        }
        const totals = calcModeTotals(printRows);
        let body = '';
        printRows.forEach((row, idx) => {
            body += `<tr>
                <td>${idx + 1}</td>
                <td>${row.Invoice_No ?? ''}</td>
                <td>${row.Invoice_Date ? siDate.toDisplay(row.Invoice_Date) : ''}</td>
                <td>${row.Customer_Name ?? ''}</td>
                <td>${row.Trans_Mode ?? '-'}</td>
                <td style="text-align:right;">${fmtAmt(row.Net_Amt)}</td>
            </tr>`;
        });
        body += `<tr>
            <td colspan="5" style="text-align:right;font-weight:bold;">Total</td>
            <td style="text-align:right;font-weight:bold;">${fmtAmt(totals.net)}</td>
        </tr>`;
        const denomTotalAmt = currentDenom
            ? (currentDenom.denom_total ?? denomTotal(currentDenom))
            : 0;
        const denomPrint = (currentDenom && totals.cash > 0 && denomTotalAmt > 0) ? `
            <div style="margin-top:14px;max-width:240px;">
                <div style="font-weight:bold;margin-bottom:6px;">Cash Denomination</div>
                <table style="width:100%;border-collapse:collapse;border:1px solid #000;">
                    ${denomPairs(currentDenom).map(([note, qty]) => `
                        <tr>
                            <td style="width:50%;border:1px solid #000;padding:6px 10px;text-align:center;font-family:monospace;font-weight:bold;">${note}</td>
                            <td style="width:50%;border:1px solid #000;padding:6px 10px;text-align:center;font-family:monospace;">${parseInt(qty, 10) || 0}</td>
                        </tr>
                    `).join('')}
                </table>
                <div style="margin-top:6px;font-weight:bold;">Total: ₹ ${fmtAmt(denomTotalAmt)}</div>
            </div>` : '';
        const html = `<!DOCTYPE html><html><head><title>Office Settlement</title>
            <style>
                * { box-sizing: border-box; }
                @page { size: A4; margin: 12mm; }
                html, body { margin: 0; padding: 0; }
                body { font-family: Arial, sans-serif; font-size: 12px; color: #000; }
                h3, h4, p { margin: 0 0 6px 0; text-align: center; }
                table { width: 100%; border-collapse: collapse; margin-top: 12px; table-layout: fixed; }
                th, td { border: 1px solid #000; padding: 4px 6px; word-wrap: break-word; }
                th { background: #f0f0f0; }
                .summary { margin-top: 14px; width: 100%; }
                .summary td { border: 1px solid #000; padding: 8px; width: 33.33%; text-align: center; }
                .summary .lbl { font-size: 11px; color: #444; }
                .summary .amt { font-size: 14px; font-weight: bold; margin-top: 4px; }
            </style></head><body>
            <h3>${orgName || 'Smart Inventory'}</h3>
            <h4>Office Settlement (Unsettled)</h4>
            <p>Agent: ${agentName || ''}${currentToken ? ' &nbsp;|&nbsp; Token: ' + currentToken : ''}</p>
            <table>
                <thead><tr>
