    $('#generateTokenBtn').on('click', function () {
        if (currentToken) {
            showTokenPopup(
                'Token already generated. Give this token to admin for settlement.',
                currentToken,
                true,
                currentDenom
            );
            return;
        }

        if (!printRows.length) {
            Swal.fire('Info', 'No unsettled sales to generate token', 'info');
            return;
        }

        const cashTotal = calcModeTotals(printRows).cash;
        openDenominationForm(cashTotal).then(function (result) {
            if (!result.isConfirmed) return;
            const denom = result.value || {};

            $.ajax({
                url: generateTokenUrl,
                method: 'POST',
                data: Object.assign({ _token: csrfToken }, denom),
                success: function (res) {
                    setActiveToken(res.settle_token || '', res.denomination || {
                        coin: denom.coin, rs_5: denom.rs_5, rs_10: denom.rs_10, rs_20: denom.rs_20,
                        rs_50: denom.rs_50, rs_100: denom.rs_100, rs_200: denom.rs_200, rs_500: denom.rs_500,
                        denom_total: denomTotal(denom), token: res.settle_token
                    });
                    showTokenPopup(res.message || '', res.settle_token || '', !!res.already_exists, currentDenom);
                },
                error: function (xhr) {
                    Swal.fire('Error', xhr.responseJSON?.message || 'Failed to generate token', 'error');
                }
            });
        });
    });

    setActiveToken(currentToken, null);
    loadSettlementData();
